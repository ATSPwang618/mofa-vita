param([string]$Compiler = $env:KNIFE_VITA_CGC)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

# Use the user's locally installed compiler; no compiler or runtime module is copied.
if ([string]::IsNullOrWhiteSpace($Compiler)) {
    foreach ($name in @('psp2cgc', 'psp2cgc.exe')) {
        $command = Get-Command $name -CommandType Application -ErrorAction SilentlyContinue
        if ($command) { $Compiler = $command.Source; break }
    }
}
if ([string]::IsNullOrWhiteSpace($Compiler)) {
    throw 'psp2cgc was not found. Set KNIFE_VITA_CGC, pass -Compiler, or add psp2cgc to PATH.'
}
if (-not (Test-Path -LiteralPath $Compiler -PathType Leaf)) {
    $command = Get-Command $Compiler -CommandType Application -ErrorAction SilentlyContinue
    if (-not $command) { throw "Shader compiler was not found: $Compiler. Set KNIFE_VITA_CGC or pass -Compiler with its executable path." }
    $Compiler = $command.Source
}
$compilerPath = (Get-Item -LiteralPath $Compiler).FullName
$root = (Get-Item -LiteralPath $PSScriptRoot).Parent.FullName
$sourceRoot = Join-Path $root 'knife/vita/shaders'
$outputRoot = Join-Path $root '.work/vita/shaders'
$headerRoot = Join-Path $sourceRoot 'generated'
$logRoot = Join-Path $root 'doc/logs/vita'
foreach ($directory in @($outputRoot, $headerRoot, $logRoot)) {
    [void][IO.Directory]::CreateDirectory($directory)
}
$utf8 = [Text.UTF8Encoding]::new($false)
$logPath = Join-Path $logRoot 'shader-build.log'
[IO.File]::WriteAllText($logPath, '', $utf8)

function Write-BuildLog([string]$Message) {
    [IO.File]::AppendAllText($logPath, $Message + "`n", $utf8)
    Write-Host $Message
}
function Get-Digest([string]$Path) {
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}
function Get-RelativePath([string]$Path) {
    if (-not $Path.StartsWith($root + [IO.Path]::DirectorySeparatorChar, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Output is outside the workspace: $Path"
    }
    return $Path.Substring($root.Length + 1).Replace('\', '/')
}
function Invoke-Compiler([string[]]$Arguments) {
    Write-BuildLog ('psp2cgc ' + ($Arguments -join ' '))
    $lines = @(& $compilerPath @Arguments 2>&1)
    $code = $LASTEXITCODE
    foreach ($line in $lines) { Write-BuildLog ([string]$line) }
    if ($code -ne 0) { throw "Offline shader compilation failed with exit $code" }
}
function Assert-Gxp([string]$Path) {
    $bytes = [IO.File]::ReadAllBytes($Path)
    # GXP magic and bounded minimum/maximum size are preliminary file checks.
    # sceGxmProgramCheck and shader patcher verification are runtime gates.
    if ($bytes.Length -lt 32 -or $bytes.Length -gt 1048576) {
        throw "Invalid GXP size: $Path ($($bytes.Length))"
    }
    if ($bytes[0] -ne 0x47 -or $bytes[1] -ne 0x58 -or $bytes[2] -ne 0x50 -or $bytes[3] -ne 0) {
        throw "Invalid GXP magic: $Path"
    }
    return ,$bytes
}

Write-BuildLog ('Compiler: ' + $compilerPath)
$compilerVersion = @(& $compilerPath -version 2>&1)
$versionExit = $LASTEXITCODE
foreach ($line in $compilerVersion) { Write-BuildLog ([string]$line) }
if ($versionExit -ne 0) { throw 'Cannot query shader compiler version' }
$commonFlags = @('-entry', 'main', '-O3', '-bestprecision', '-nofastmath', '-W3', '-Werror', '-Wperf', '-nofx', '-nocolor', '-lang', 'en')
$specifications = @(
    @{ Name = 'quad_v'; Profile = 'sce_vp_psp2'; Symbol = 'knife_quad_v_gxp' },
    @{ Name = 'quad_f'; Profile = 'sce_fp_psp2'; Symbol = 'knife_quad_f_gxp' }
)
$records = [Collections.Generic.List[object]]::new()
$header = [Text.StringBuilder]::new()
[void]$header.Append("/* Generated by tools/compile-vita-shaders.ps1; do not edit. */`n")
[void]$header.Append("/* Basic texture/color probe only; SDK runtime verification is separate. */`n")
[void]$header.Append("#ifndef KNIFE_VITA_GENERATED_SHADERS_H`n#define KNIFE_VITA_GENERATED_SHADERS_H`n`n")
[void]$header.Append("#if defined(__cplusplus)`n#define KNIFE_GXP_ALIGN alignas(4)`n#else`n#define KNIFE_GXP_ALIGN _Alignas(4)`n#endif`n`n")
foreach ($specification in $specifications) {
    $source = Join-Path $sourceRoot ($specification.Name + '.cg')
    $output = Join-Path $outputRoot ($specification.Name + '.gxp')
    $repeat = Join-Path $outputRoot ($specification.Name + '.repeat.gxp')
    $arguments = @('-profile', $specification.Profile) + $commonFlags
    Invoke-Compiler ($arguments + @('-o', $output, $source))
    $bytes = Assert-Gxp $output
    Invoke-Compiler ($arguments + @('-o', $repeat, $source))
    [void](Assert-Gxp $repeat)
    $digest = Get-Digest $output
    $repeatDigest = Get-Digest $repeat
    if ($digest -ne $repeatDigest) { throw "Repeated compiler output differs for $($specification.Name)" }
    [void]$header.Append("/* SHA-256: $digest */`n")
    [void]$header.Append("KNIFE_GXP_ALIGN static const unsigned char $($specification.Symbol)[] = {`n")
    for ($index = 0; $index -lt $bytes.Length; $index += 12) {
        $last = [Math]::Min($index + 11, $bytes.Length - 1)
        $row = for ($cursor = $index; $cursor -le $last; $cursor++) { '0x{0:x2}' -f $bytes[$cursor] }
        [void]$header.Append('    ' + ($row -join ', ') + ",`n")
    }
    [void]$header.Append("};`n")
    [void]$header.Append("static const unsigned int $($specification.Symbol)_size = sizeof($($specification.Symbol));`n`n")
    $records.Add([ordered]@{
        name = $specification.Name
        profile = $specification.Profile
        entry = 'main'
        flags = $arguments
        source = [ordered]@{ path = Get-RelativePath $source; sha256 = Get-Digest $source }
        artifact = [ordered]@{ path = Get-RelativePath $output; bytes = $bytes.Length; sha256 = $digest; magic = '47585000' }
        repeated_artifact = [ordered]@{ path = Get-RelativePath $repeat; sha256 = $repeatDigest }
        repeated_compile_identical = $true
        symbol = $specification.Symbol
    })
    Write-BuildLog ("Validated $($specification.Name): $($bytes.Length) bytes, SHA-256 $digest; repeated output identical")
}
[void]$header.Append("#undef KNIFE_GXP_ALIGN`n#endif`n")
$headerPath = Join-Path $headerRoot 'shaders.h'
[IO.File]::WriteAllText($headerPath, $header.ToString(), $utf8)
$receipt = [ordered]@{
    built_at = [DateTime]::UtcNow.ToString('o')
    scope = 'Basic quad texture/color shaders for the GXM development probe; game effects are not covered'
    compiler = [ordered]@{ path = $compilerPath.Replace('\', '/'); sha256 = Get-Digest $compilerPath; version = $compilerVersion -join "`n" }
    entrypoint = 'tools/compile-vita-shaders.ps1'
    entrypoint_sha256 = Get-Digest $PSCommandPath
    shaders = $records.ToArray()
    header = [ordered]@{ path = Get-RelativePath $headerPath; bytes = (Get-Item -LiteralPath $headerPath).Length; sha256 = Get-Digest $headerPath; alignment_bytes = 4 }
    sdk_program_check_verified = $false
    patcher_link_verified = $false
    runtime_verified = $false
    hardware_verified = $false
}
$receiptPath = Join-Path $root 'doc/vita-shaders-build.json'
[IO.File]::WriteAllText($receiptPath, ($receipt | ConvertTo-Json -Depth 8) + "`n", $utf8)
Write-BuildLog ('Generated header: ' + (Get-RelativePath $headerPath))
Write-BuildLog ('Build receipt: ' + (Get-RelativePath $receiptPath))
