#!/usr/bin/env python3
"""Generate compile-time full-source PS entries from the authored generic body.

This produces Cg source only, not GXP. KNIFE_PS_FULL_OP selects one operation
for fs_ps_operation_fetch; texture/source preparation remains ps_source.
"""
import argparse
import hashlib
from pathlib import Path
import re
import textwrap

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "knife/vita/shaders/effects.cg"
BEGIN = "// BEGIN GENERATED PS OPERATIONS\n"
END = "// END GENERATED PS OPERATIONS\n"


def braced(text, start):
    opening = text.index("{", start)
    depth, end = 1, opening + 1
    while depth:
        depth += (text[end] == "{") - (text[end] == "}")
        end += 1
    return text[opening + 1:end - 1], end


def operation_bodies(generic):
    bodies = {}
    pattern = r"\b(?:else\s+)?if\s*\((op == [^)]+)\)\s*\{"
    for match in re.finditer(pattern, generic):
        # Top-level generic branches have '.0'; the nested op12 check is
        # intentionally not a branch selector and is resolved below.
        ops = [int(op) for op in re.findall(r"op == (\d+)\.0", match[1])]
        if not ops:
            continue
        code, _ = braced(generic, match.start())
        for op in ops:
            if op in bodies:
                raise ValueError(f"duplicate generic operation {op}")
            bodies[op] = textwrap.dedent(code).strip()
    if set(bodies) != set(range(1, 25)):
        raise ValueError(f"generic operation inventory changed: {sorted(bodies)}")
    normalization = "if (op == 12) { h = min(s / t.a, one); }"
    if normalization not in bodies[11] or bodies[11] != bodies[12]:
        raise ValueError("generic HardLight/normalized HardLight branch changed")
    bodies[11] = bodies[11].replace(normalization, "")
    bodies[12] = bodies[12].replace(normalization, "h = min(s / t.a, one);")
    return bodies


def native_body(op, code):
    # Preserve the generic alpha rule exactly. The other operations use ca or
    # ignore sampled alpha; op21 keeps its own opacity early return in the body.
    alpha_guard = op <= 15 or op in (19, 20, 23, 24)
    uses = lambda name: re.search(r"\b" + name + r"\b", code) is not None
    lines = []
    for name, declaration in [
        ("t", "float4 t = source.texel;"),
        ("s", "float3 s = source.source;"),
        ("ca", "float ca = source.opacity;"),
    ]:
        if uses(name):
            lines.append(declaration)
    if uses("a") or alpha_guard:
        lines.append("float a = source.alpha;")
    if uses("d4"):
        lines.append("float4 d4 = native_unpack(destination);")
    if uses("d"):
        lines.append("float3 d = d4.rgb;" if uses("d4") else "float3 d = native_unpack(destination).rgb;")
    for name, value in (("one", "1.0"), ("zero", "0.0")):
        if uses(name):
            lines.append(f"const float3 {name} = float3({value}, {value}, {value});")
    if alpha_guard:
        lines.append("if (min(a, 0.0) == a) { return destination; }")

    def native_return(match):
        value = match[1].strip()
        return "return destination;" if value == "d4" else f"return native_pack({value});"

    code = re.sub(r"\breturn\s+([^;]+);", native_return, code)
    if re.search(r"\bop\b", code):
        raise ValueError(f"operation {op} still depends on the runtime selector")
    return textwrap.indent("\n".join(lines) + "\n" + code, "    ")


def generated_block(text):
    generic, _ = braced(text, text.index("float4 ps_apply("))
    digest = hashlib.sha256(generic.encode()).hexdigest()
    bodies = operation_bodies(generic)
    lines = [BEGIN.rstrip(),
        "// Generated by tools/generate-ps-operation-shaders.py; Cg source, not GXP.",
        f"// ps_apply body SHA-256: {digest}",
        "// IDs64..87 select OP1..24 with KNIFE_PS_FULL_OP at compile time.",
        "// Every operation retains full ps_source material preparation and its",
        "// original alpha rule, F32 equations, and native RGBA8 store boundary.",
        "#ifdef KNIFE_PS_FULL_OP",
        "__nativecolor __regformat unsigned char4 fs_ps_operation_fetch(FragmentInput i,",
        "    __regformat unsigned char4 destination : FRAGCOLOR) : COLOR {",
        "    PsSample source = ps_source(i);"]
    for op in range(1, 25):
        lines.append(("#if" if op == 1 else "#elif") + f" KNIFE_PS_FULL_OP == {op}")
        lines.append(native_body(op, bodies[op]))
    lines += ["#else", "#error Unsupported KNIFE_PS_FULL_OP", "#endif", "}", "#endif", END.rstrip()]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Reject stale generated Cg without writing")
    args = parser.parse_args()
    text = SOURCE.read_text()
    block = generated_block(text)
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END)
        result = text[:start] + block + text[end:]
    else:
        anchor = "// Complete-source PsOp7:"
        index = text.index(anchor)
        result = text[:index] + block + "\n" + text[index:]
    if args.check:
        if result != text:
            raise SystemExit("generated PS Cg is stale; run python3 tools/generate-ps-operation-shaders.py")
    else:
        with SOURCE.open("w", newline="\n") as output:
            output.write(result)
    print("PS operations 1..24 source verified; no GXP compilation performed")


if __name__ == "__main__":
    main()
