#!/usr/bin/env python3
"""Embed the authored Cg and bind cache identities to its exact source bytes."""
import hashlib
import json
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
source = ROOT / "knife/vita/shaders/effects.cg"
output = ROOT / "knife/vita/shaders/generated/runtime_source.h"
data = source.read_bytes()
text = data.decode("utf-8")
lines = ["/* Generated by tools/generate-runtime-shaders.py; authored source only. */\n",
         "#ifndef KNIFE_RUNTIME_SOURCE_H\n#define KNIFE_RUNTIME_SOURCE_H\n",
         f'#define KNIFE_RUNTIME_SOURCE_SHA256 "{hashlib.sha256(data).hexdigest()}"\n',
         '#define KNIFE_RUNTIME_COMPILER_SHA256 "0c58b5d3e1cc47d9837b8c59ab6f3c299bfe7adf55a83f547d553f9fbb776552"\n',
         '#define KNIFE_RUNTIME_COMPILER_BYTES 1776523u\n',
         '#define KNIFE_RUNTIME_COMPILER_INFO_OFFSET 0x276a40u\n',
         '#define KNIFE_RUNTIME_ENTRY_ABI 2u\n',
         "static const char knife_runtime_effects_source[] =\n"]
for line in text.splitlines(keepends=True):
    lines.append("    " + json.dumps(line, ensure_ascii=True) + "\n")
lines.append("    ;\n#endif\n")
generated = "".join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Reject a stale embedded Cg source without modifying it")
args = parser.parse_args()
if args.check:
    if not output.exists() or output.read_text() != generated:
        raise SystemExit("runtime_source.h is stale; run python3 tools/generate-runtime-shaders.py")
else:
    output.write_text(generated)
print(output.relative_to(ROOT), hashlib.sha256(data).hexdigest())
