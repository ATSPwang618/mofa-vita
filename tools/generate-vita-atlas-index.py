#!/usr/bin/env python3
"""Generate manifest-bound metadata-only KATL registrations; never decode pixels."""
import argparse,hashlib,json,mmap,struct,sys,zlib
from pathlib import Path
import vita_image_metadata as scan

def hash_file(path):
 digest=hashlib.sha256()
 with path.open('rb') as source:
  for block in iter(lambda:source.read(1024*1024),b''):digest.update(block)
 return digest.hexdigest()

def generate(root,base_assets=None):
 def asset(name):
  p=root/name
  return p if p.is_file()or base_assets is None else base_assets/name
 manifest_path=root/'vita-540p-assets.json';raw_manifest=manifest_path.read_bytes()
 manifest=json.loads(raw_manifest);expected={r['path']:r for r in manifest['files']}
 for suffix in ['hed','nam','mrg']:
  p=asset(f'allui.{suffix}'); ref=expected[p.name]
  if p.stat().st_size!=ref['bytes'] or hash_file(p)!=ref['sha256']:
   raise ValueError(f'archive manifest mismatch: {p.name}')
 hed=asset('allui.hed').read_bytes();nam=asset('allui.nam').read_bytes();out=[];totals={'atlases':0,'members':0,'gxt':0,'other':0}
 with asset('allui.mrg').open('rb') as f,mmap.mmap(f.fileno(),0,access=mmap.ACCESS_READ) as mm:
  for index in range(len(hed)//8):
   sector,stored,unpacked=struct.unpack_from('<IHH',hed,index*8)
   if sector==0xffffffff:break
   name=nam[index*32:(index+1)*32].split(b'\0')[0].split(b'\r')[0].decode()
   if not stored or name=='NOFILE.EXISTS':continue
   begin=sector*2048
   if begin+stored*2048>len(mm):raise ValueError('entry extent')
   magic=mm[begin:begin+4]
   if magic in (b'NXCX',b'NXGX'):
    length,compressed=struct.unpack_from('<II',mm,begin+4)
    if length>scan.CAP or compressed+16>stored*2048:raise ValueError('NX bounds')
    decoder=zlib.decompressobj(31 if magic==b'NXGX' else 15)
    data=decoder.decompress(mm[begin+16:begin+16+compressed],length+1)
    if len(data)!=length or not decoder.eof or decoder.unused_data or decoder.unconsumed_tail:raise ValueError('NX stream')
   else:data=mm[begin:begin+stored*2048]
   if data[:4]!=b'KATL':continue
   scan.images_in(data) # exact KATL/KIMG/GXT envelope, padding and payload checks
   version,count=struct.unpack_from('<II',data,4);p=12;members=[]
   for _ in range(count):
    nl,il=struct.unpack_from('<II',data,p);p+=8
    member=data[p:p+nl].decode();p+=nl;image=data[p:p+il];info=scan.image_info(image)
    if info['envelope_bytes']!=il:raise ValueError('member has unexpected tail')
    logical=info['logical'];physical=info['physical'];gxt='None'
    if info['codec']in(8,9):
     layout,fmt=struct.unpack_from('<II',image,32+48)
     gxt=f'Some(IndexedGxtMetadata {{ layout: {layout}, format: {fmt}, payload_bytes: {info["gpu_payload_bytes"]} }})';totals['gxt']+=1
    else:totals['other']+=1
    members.append(f'        Member {{ name: {json.dumps(member,ensure_ascii=False)}, offset: {p}, len: {il}, logical: {logical}, physical: {physical}, encoding: {info["codec"]}, gxt: {gxt} }},')
    p+=il
   direct='true' if magic==b'KATL' else 'false'
   out.append(f'    Atlas {{ index: {index}, entry: {json.dumps(name)}, offset: {begin}, stored_sectors: {stored}, unpacked_sectors: {unpacked}, decoded_bytes: {len(data)}, direct: {direct}, members: &[\n'+ '\n'.join(members)+'\n    ] },')
   totals['atlases']+=1;totals['members']+=count
 manifest_hash=hashlib.sha256(raw_manifest).hexdigest()
 text='// Generated by tools/generate-vita-atlas-index.py; immutable metadata, no image payload.\n'
 text+=f'pub const MANIFEST: &str = "{manifest_hash}";\n'
 text+='pub static ATLASES: &[Atlas] = &[\n'+'\n'.join(out)+'\n];\n'
 return text,dict(**totals,manifest_sha256=manifest_hash,source_sha256=hashlib.sha256(text.encode()).hexdigest())

if __name__=='__main__':
 parser=argparse.ArgumentParser();parser.add_argument('assets',type=Path);parser.add_argument('output',type=Path);parser.add_argument('--check',action='store_true');parser.add_argument('--base-assets',type=Path);args=parser.parse_args()
 text,summary=generate(args.assets,args.base_assets)
 if args.check:
  if args.output.read_text(encoding='utf-8')!=text:raise ValueError('generated atlas index is stale')
 else:args.output.parent.mkdir(parents=True,exist_ok=True);args.output.write_text(text,encoding='utf-8',newline='\n')
 print(json.dumps(summary,sort_keys=True))
