"""Pin bounded startup checks to the verified external 270p asset pack.

The generated Rust profile travels inside the VPK. No game bytes are embedded.
--check compares without writing. Full SHA-256 verification occurs here, on PC;
Vita reads small metadata files and only the edges of large payloads at startup.
"""
import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import zlib

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "dist/Witch-on-the-Holy-Night-Chengkong-270p-Vita/assets"
OUTPUT = ROOT / "knife/knife-platform-vita/src/asset_profile_270p.rs"
MARKER = "vita-270p-assets.json"


def generate():
    marker = (ASSETS / MARKER).read_bytes()
    manifest = json.loads(marker)
    assert manifest["schema"] in ("knife-270p-assets-v1", "knife-270p-assets-v2")
    if manifest["schema"] == "knife-270p-assets-v2":
        assert manifest["method"] == "270p-scenes-540p-ui-preserve-logical-v1"
        assert manifest["composite"] == [960, 540]
        assert manifest["ui_policy"]["archive"] == "allui"
        assert manifest["ui_policy"]["max_physical"] == [960, 540]
        assert manifest["ui_policy"]["runtime_hd_fallback"] is False
    assert manifest["render"] == [480, 270] and manifest["display"] == [960, 540]
    assert manifest["languages"] == ["en", "zc"]
    assert manifest["codecs"] == [1, 2, 7]
    assert manifest["verification"]["all_pass"] and not manifest["verification"]["hd_fallback"]
    files = {r["path"]: r for r in manifest["files"]}
    # Native GXM uses embedded GXP shaders. Keep original BNSh and conversion
    # audit JSON outside this runtime contract; the complete offline audit covers them.
    names = sorted(n for n in files if not n.endswith(".270p.json")
                   and not n.startswith(("stream/", "shader/")))
    streams = sorted(n for n in files if n.startswith("stream/"))
    assert len(streams) == 9470
    names += [streams[0], streams[-1]]
    records = [(MARKER, marker)]
    rows = []
    total_read = 0
    for name in [MARKER] + names:
        pure = PurePosixPath(name)
        assert not pure.is_absolute() and ".." not in pure.parts and ":" not in name and "\\" not in name
        p = ASSETS / name
        size = p.stat().st_size
        if name != MARKER:
            expected = files[name]
            assert size == expected["bytes"], name
            with p.open("rb") as f:
                assert hashlib.file_digest(f, "sha256").hexdigest() == expected["sha256"], name
        if name == MARKER or size <= 1024 * 1024:
            data = p.read_bytes()
            content = f"ContentCheck::Full(0x{zlib.crc32(data):08x})"
            total_read += size
        else:
            with p.open("rb") as f:
                first = zlib.crc32(f.read(4096))
                f.seek(size - 4096)
                last = zlib.crc32(f.read(4096))
            content = f"ContentCheck::Edges {{ first: 0x{first:08x}, last: 0x{last:08x} }}"
            total_read += 8192
        rows.append(f'    FileSpec {{ path: "{name}", bytes: {size}, content: {content} }},')
    return ("// Generated by tools/generate_vita_asset_profile.py; no game payloads.\n"
            f"// External manifest SHA-256: {hashlib.sha256(marker).hexdigest()}\n"
            f"// {len(rows)} key files, {total_read} bytes read once at startup, one 8192-byte buffer.\n"
            "// Large-file checks cover exact length and first/last 4096 bytes only.\n"
            "const PROFILE: &[FileSpec] = &[\n" + "\n".join(rows) + "\n];\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        assert OUTPUT.read_text(encoding="utf-8") == generated, "Embedded 270p asset profile is stale"
    else:
        OUTPUT.write_text(generated, encoding="utf-8", newline="\n")
    print(generated.splitlines()[2])
